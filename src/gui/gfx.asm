; =============================================================================
; X86ASMOS - Graphics Driver (VBE 32bpp, double-buffered)
; -----------------------------------------------------------------------------
; Reads the video mode the bootloader selected (VBE linear framebuffer),
; identity-maps the framebuffer into the page tables, and provides a
; double-buffered drawing surface plus an 8x8 bitmap font.
;
; All drawing goes to a back buffer (allocated from the heap); gfx_blit copies
; it to the real framebuffer in one shot, avoiding flicker/tearing.
;
; Colours are 0x00RRGGBB. Coordinates are (x, y) with origin at top-left.
;
; Public interface:
;   gfx_init       - read mode, map framebuffer, allocate back buffer
;   gfx_clear      - EAX = colour; fill the back buffer
;   gfx_pixel      - EAX=x, EBX=y, ECX=colour
;   gfx_fillrect   - EAX=x, EBX=y, ECX=w, EDX=h, ESI=colour
;   gfx_rect       - EAX=x, EBX=y, ECX=w, EDX=h, ESI=colour (outline)
;   gfx_char       - EAX=x, EBX=y, ECX=char, EDX=colour (8x8 font)
;   gfx_string     - EAX=x, EBX=y, ESI=string, EDX=colour
;   gfx_blit       - copy back buffer to framebuffer
; =============================================================================

; Boot info video offsets (match stage2).
BOOT_VIDEO_OFF equ 0x610
VIDEO_W_OFF    equ 0
VIDEO_H_OFF    equ 2
VIDEO_BPP_OFF  equ 4
VIDEO_PITCH_OFF equ 5
VIDEO_FB_OFF   equ 7

; Globals
gfx_width:      dd 0
gfx_height:     dd 0
gfx_bpp:        dd 0
gfx_pitch:      dd 0
gfx_fb:         dd 0        ; framebuffer address (virtual)
gfx_back:       dd 0        ; back buffer address
gfx_fb_size:    dd 0        ; framebuffer size in bytes

; -----------------------------------------------------------------------------
gfx_init:
    pusha

    mov esi, [boot_info_ptr]
    add esi, BOOT_VIDEO_OFF

    movzx eax, word [esi + VIDEO_W_OFF]
    mov [gfx_width], eax
    movzx eax, word [esi + VIDEO_H_OFF]
    mov [gfx_height], eax
    movzx eax, byte [esi + VIDEO_BPP_OFF]
    mov [gfx_bpp], eax
    movzx eax, word [esi + VIDEO_PITCH_OFF]
    mov [gfx_pitch], eax
    mov eax, [esi + VIDEO_FB_OFF]
    mov [gfx_fb], eax

    ; No video mode? Stay in text mode.
    cmp dword [gfx_width], 0
    je .no_video

    ; Compute framebuffer size and identity-map it (it usually lives far
    ; above the 128 MiB identity map, e.g. 0xFD000000 in QEMU).
    mov eax, [gfx_pitch]
    imul eax, [gfx_height]
    mov [gfx_fb_size], eax

    mov ebx, [gfx_fb]
    mov ecx, [gfx_fb]
    mov esi, [gfx_fb_size]
    add esi, 4095
    shr esi, 12                         ; page count (rounded up)
.map_loop:
    push ebx
    push ecx
    push esi
    mov edx, PTE_PRESENT | PTE_WRITABLE
    mov eax, PAGE_DIR
    call map_page
    pop esi
    pop ecx
    pop ebx
    add ebx, 4096
    add ecx, 4096
    dec esi
    jnz .map_loop

    ; Flush the TLB.
    mov eax, PAGE_DIR
    mov cr3, eax

    ; Allocate the back buffer.
    mov eax, [gfx_fb_size]
    call kmalloc
    mov [gfx_back], eax

    mov eax, 0x00000000
    call gfx_clear

.no_video:
    popa
    ret

; -----------------------------------------------------------------------------
; gfx_clear - EAX = colour.
; -----------------------------------------------------------------------------
gfx_clear:
    push edi
    push ecx
    mov edi, [gfx_back]
    mov ecx, [gfx_fb_size]
    shr ecx, 2
    rep stosd
    pop ecx
    pop edi
    ret

; -----------------------------------------------------------------------------
; gfx_pixel - EAX=x, EBX=y, ECX=colour. Clips to bounds.
; -----------------------------------------------------------------------------
gfx_pixel:
    push edi
    push edx
    cmp eax, [gfx_width]
    jae .done
    cmp ebx, [gfx_height]
    jae .done
    test eax, eax
    js .done
    test ebx, ebx
    js .done
    mov edx, ebx
    imul edx, [gfx_pitch]
    lea edi, [eax * 4]
    add edx, edi
    add edx, [gfx_back]
    mov [edx], ecx
.done:
    pop edx
    pop edi
    ret

; -----------------------------------------------------------------------------
; gfx_fillrect - EAX=x, EBX=y, ECX=w, EDX=h, ESI=colour. Caller must pass
; coordinates within the framebuffer bounds.
; -----------------------------------------------------------------------------
gfx_fillrect:
    push ebx
    push ecx
    push edx
    push esi
    push edi
    push ebp

    mov ebp, [gfx_back]
    mov edi, ebx                        ; y
    imul edi, [gfx_pitch]
    add ebp, edi
    lea edi, [eax * 4]                  ; x * 4
    add ebp, edi                        ; EBP = top-left pixel address

    mov edi, edx                        ; EDI = rows remaining
    mov eax, esi                        ; EAX = colour

.row:
    test edi, edi
    jz .done
    push ecx
    push edi
    mov edi, ebp
    rep stosd                           ; fill this row
    pop edi
    pop ecx
    add ebp, [gfx_pitch]
    dec edi
    jmp .row

.done:
    pop ebp
    pop edi
    pop esi
    pop edx
    pop ecx
    pop ebx
    ret

; -----------------------------------------------------------------------------
; gfx_rect - EAX=x, EBX=y, ECX=w, EDX=h, ESI=colour (1-pixel outline).
; -----------------------------------------------------------------------------
gfx_rect:
    push eax                            ; [esp+16] x
    push ebx                            ; [esp+12] y
    push ecx                            ; [esp+8]  w
    push edx                            ; [esp+4]  h
    push esi                            ; [esp+0]  colour

    ; top edge (x, y, w, 1)
    mov eax, [esp+16]
    mov ebx, [esp+12]
    mov ecx, [esp+8]
    mov edx, 1
    mov esi, [esp+0]
    call gfx_fillrect

    ; bottom edge (x, y+h-1, w, 1)
    mov eax, [esp+16]
    mov ebx, [esp+12]
    add ebx, [esp+4]
    dec ebx
    mov ecx, [esp+8]
    mov edx, 1
    mov esi, [esp+0]
    call gfx_fillrect

    ; left edge (x, y, 1, h)
    mov eax, [esp+16]
    mov ebx, [esp+12]
    mov ecx, 1
    mov edx, [esp+4]
    mov esi, [esp+0]
    call gfx_fillrect

    ; right edge (x+w-1, y, 1, h)
    mov eax, [esp+16]
    add eax, [esp+8]
    dec eax
    mov ebx, [esp+12]
    mov ecx, 1
    mov edx, [esp+4]
    mov esi, [esp+0]
    call gfx_fillrect

    add esp, 20
    ret

; -----------------------------------------------------------------------------
; gfx_char - EAX=x, EBX=y, ECX=char, EDX=colour (8x8 bitmap font).
; -----------------------------------------------------------------------------
gfx_char:
    push eax                            ; [esp+12] x
    push ebx                            ; [esp+8]  y
    push ecx                            ; [esp+4]  char
    push edx                            ; [esp+0]  colour

    mov esi, ecx
    sub esi, 0x20
    shl esi, 3
    add esi, font8x8                    ; ESI = glyph base

    xor ebp, ebp                        ; row
.row_loop:
    movzx edi, byte [esi + ebp]         ; EDI = row bits

    xor ebx, ebx                        ; col
.col_loop:
    mov eax, 7
    sub eax, ebx                        ; bit index = 7 - col
    mov edx, 1
    mov ecx, eax
    shl edx, cl
    test edi, edx
    jz .skip

    mov eax, [esp + 12]                 ; x
    add eax, ebx
    mov edx, [esp + 8]                  ; y
    add edx, ebp
    mov ecx, [esp + 0]                  ; colour
    push ebx
    push ebp
    push edi
    mov ebx, edx
    call gfx_pixel
    pop edi
    pop ebp
    pop ebx

.skip:
    inc ebx
    cmp ebx, 8
    jb .col_loop

    inc ebp
    cmp ebp, 8
    jb .row_loop

    add esp, 16
    ret

; -----------------------------------------------------------------------------
; gfx_string - EAX=x, EBX=y, ESI=string, EDX=colour.
; -----------------------------------------------------------------------------
gfx_string:
    push eax                            ; [esp+12] x
    push ebx                            ; [esp+8]  y
    push esi                            ; [esp+4]  string pointer
    push edx                            ; [esp+0]  colour

.loop:
    mov esi, [esp+4]                    ; reload string pointer
    movzx ecx, byte [esi]
    test cl, cl
    jz .done
    inc esi
    mov [esp+4], esi                    ; save advanced pointer

    mov eax, [esp+12]                   ; x
    mov ebx, [esp+8]                    ; y
    mov edx, [esp+0]                    ; colour
    call gfx_char                       ; ECX = char

    add dword [esp+12], 8               ; advance x
    jmp .loop

.done:
    add esp, 16
    ret

; -----------------------------------------------------------------------------
; gfx_blit - copy the back buffer to the framebuffer.
; -----------------------------------------------------------------------------
gfx_blit:
    push esi
    push edi
    push ecx
    mov esi, [gfx_back]
    mov edi, [gfx_fb]
    mov ecx, [gfx_fb_size]
    shr ecx, 2
    rep movsd
    pop ecx
    pop edi
    pop esi
    ret

